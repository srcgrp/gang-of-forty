export type CartItem = { productId: number; name: string; price: number; quantity: number };
export type Cart = CartItem[];
export type Product = { id: number; categoryId: number; name: string; emoji: string; unit: string; price: number; tags: string[] };
export type Stock = { updatedAt: string; items: Record<string, number> };
export type Category = { id: number; slug: string; name: string; emoji: string; color: string };
export type Categories = Category[];
export type Offer = { productId: number; percent: number; label: string };
export type Offers = Offer[];
export type ProductData = { products: Product[]; offers: Offers };
export type SuggestionsData = { products: Product[]; stock: Stock; offers: Offers };
export type Schedule = { days: string; time: string };
export type MenuItem = { label: string; href: string };
export type HelpItem = { label: string; href: string };
export type Shop = { name: string; slogan: string; owner: string; city: string; phone: string; hours: { open: string; close: string }; deliveryFee: number; freeDeliveryOver: number; currency: string; notice: string; about: string; address: string; schedule: Schedule[]; menu: MenuItem[]; help: HelpItem[]; copyright: string };
export type ShopData = { shop: Shop; categories: Categories };
export type HomeSlide = { emoji: string; title: string; text: string; cta: { href: string; label: string } };
export type Promo = { href: string; color: string; emoji: string; text: string };
export type HomeCarousel = { id: string; title: string; emoji: string; source?: 'offers'; categoryId?: number };
export type Home = { hero: HomeSlide; side: HomeSlide; promos: Promo[]; carousels: HomeCarousel[] };
export type ProductCardData = { product: Product; price: number; originalPrice?: number; discountPercent?: number; outOfStock?: boolean };
export type LoadState = { status: 'loading' } | { status: 'success'; products: Product[] } | { status: 'empty' } | { status: 'error'; message: string };
